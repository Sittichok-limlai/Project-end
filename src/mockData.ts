// Total 120 rooms across 4 floors (Floors 1-4, 30 rooms per floor)
export const initialRooms: Room[] = Array.from({ length: 120 }, (_, index) => {
  const floor = Math.floor(index / 30) + 1;
  const roomSeq = (index % 30) + 1;
  const roomNumber = `${floor}${roomSeq.toString().padStart(2, '0')}`;
  
  // Distribute statuses: 108 occupied (90%), 8 vacant, 3 cleaning, 1 maintenance
  let status: Room['status'] = 'occupied';
  if (index === 5 || index === 18 || index === 42 || index === 65 || index === 79 || index === 95 || index === 110 || index === 118) {
    status = 'vacant';
  } else if (index === 12 || index === 54 || index === 88) {
    status = 'cleaning';
  } else if (index === 33) {
    status = 'maintenance';
  }

  const roomType = roomSeq <= 15 
    ? 'เตียงเดี่ยว (Standard)' 
    : roomSeq <= 25 
      ? 'เตียงคู่ (Deluxe)' 
      : 'ห้องสตูดิโอ (VIP)';

  const price = roomType === 'เตียงเดี่ยว (Standard)' ? 4500 : roomType === 'เตียงคู่ (Deluxe)' ? 5800 : 7200;

  return {
    id: `room-${roomNumber}`,
    roomNumber,
    floor,
    building: 'อาคาร A (นิวาเรสซิเดนซ์)',
    type: roomType,
    price,
    status,
    residentName: status === 'occupied' ? `ผู้พักห้อง ${roomNumber}` : undefined,
    residentId: status === 'occupied' ? `res-${roomNumber}` : undefined,
    phone: status === 'occupied' ? `08${Math.floor(10000000 + Math.random() * 90000000)}` : undefined,
    checkInDate: status === 'occupied' ? '1 มิ.ย. 2568' : undefined,
    airConditioner: true,
  };
});

